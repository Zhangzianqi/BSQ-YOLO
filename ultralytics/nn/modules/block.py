class AConv(nn.Module):
    """AConv."""

    def __init__(self, c1: int, c2: int):
        """Initialize AConv module.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
        """
        super().__init__()
        self.cv1 = Conv(c1, c2, 3, 2, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass through AConv layer."""
        x = torch.nn.functional.avg_pool2d(x, 2, 1, 0, False, True)
        return self.cv1(x)


class ADown(nn.Module):
    """ADown."""

    def __init__(self, c1: int, c2: int):
        """Initialize ADown module.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
        """
        super().__init__()
        self.c = c2 // 2
        self.cv1 = Conv(c1 // 2, self.c, 3, 2, 1)
        self.cv2 = Conv(c1 // 2, self.c, 1, 1, 0)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass through ADown layer."""
        x = torch.nn.functional.avg_pool2d(x, 2, 1, 0, False, True)
        x1, x2 = x.chunk(2, 1)
        x1 = self.cv1(x1)
        x2 = torch.nn.functional.max_pool2d(x2, 3, 2, 1)
        x2 = self.cv2(x2)
        return torch.cat((x1, x2), 1)

class AAGSDown(nn.Module):
    """Anti-aliased dual-path GS-style downsampling."""

    def __init__(self, c1: int, c2: int):
        super().__init__()

        if c1 % 2 != 0 or c2 % 2 != 0:
            raise ValueError(
                f"AAGSDown requires even channels, got c1={c1}, c2={c2}"
            )

        c1_half = c1 // 2
        c2_half = c2 // 2

        # Low-frequency branch:
        # AvgPool suppresses high-frequency water-surface aliasing.
        self.low_dw = DWConv(
            c1_half,
            c1_half,
            k=3,
            s=1,
        )
        self.low_pw = Conv(
            c1_half,
            c2_half,
            k=1,
            s=1,
        )

        # Peak-preserving branch:
        # MaxPool retains weak responses from small floating objects.
        self.peak_pw = Conv(
            c1_half,
            c2_half,
            k=1,
            s=1,
        )

    @staticmethod
    def channel_shuffle(
        x: torch.Tensor,
        groups: int = 2,
    ) -> torch.Tensor:
        b, c, h, w = x.shape

        if c % groups != 0:
            raise ValueError(
                f"Channels {c} must be divisible by groups {groups}."
            )

        return (
            x.reshape(b, groups, c // groups, h, w)
            .transpose(1, 2)
            .contiguous()
            .reshape(b, c, h, w)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        low, peak = x.chunk(2, dim=1)

        low = F.avg_pool2d(
            low,
            kernel_size=2,
            stride=2,
        )
        low = self.low_pw(
            self.low_dw(low)
        )

        peak = F.max_pool2d(
            peak,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        peak = self.peak_pw(peak)

        output = torch.cat(
            (low, peak),
            dim=1,
        )

        return self.channel_shuffle(output)

class AAGSDownV2(nn.Module):
    """
    Full-channel anti-aliased dual-path downsampling.

    Both branches read the complete input feature:
        low branch:  AvgPool -> DWConv -> PWConv
        peak branch: MaxPool -> PWConv
    """

    def __init__(self, c1: int, c2: int):
        super().__init__()

        if c2 % 2 != 0:
            raise ValueError(
                f"AAGSDownV2 requires even output channels, got c2={c2}."
            )

        c2_half = c2 // 2

        # 低频抗混叠分支：完整读取所有输入通道
        self.low_dw = DWConv(
            c1,
            c1,
            k=3,
            s=1,
        )
        self.low_pw = Conv(
            c1,
            c2_half,
            k=1,
            s=1,
        )

        # 峰值保留分支：完整读取所有输入通道
        self.peak_pw = Conv(
            c1,
            c2_half,
            k=1,
            s=1,
        )

        # 两分支相对强度，初始softmax=[0.5, 0.5]
        self.branch_logits = nn.Parameter(
            torch.zeros(2)
        )

    @staticmethod
    def channel_shuffle(
        x: torch.Tensor,
        groups: int = 2,
    ) -> torch.Tensor:
        b, c, h, w = x.shape

        if c % groups != 0:
            raise ValueError(
                f"Channels {c} must be divisible by groups {groups}."
            )

        return (
            x.reshape(b, groups, c // groups, h, w)
            .transpose(1, 2)
            .contiguous()
            .reshape(b, c, h, w)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # 低频分支：抑制下采样时的水纹和反光混叠
        low = F.avg_pool2d(
            x,
            kernel_size=2,
            stride=2,
        )
        low = self.low_pw(
            self.low_dw(low)
        )

        # 峰值分支：保留小型、弱响应垃圾目标
        peak = F.max_pool2d(
            x,
            kernel_size=3,
            stride=2,
            padding=1,
        )
        peak = self.peak_pw(peak)

        # 乘以2保证零初始化时两个分支的初始缩放均为1
        weights = (
            2.0 * torch.softmax(
                self.branch_logits,
                dim=0,
            )
        ).to(dtype=x.dtype)

        output = torch.cat(
            (
                weights[0] * low,
                weights[1] * peak,
            ),
            dim=1,
        )

        return self.channel_shuffle(
            output,
            groups=2,
        )

class SCADown(nn.Module):
    """
    Surface-Contrast Anti-Aliased Downsampling.

    Branch 1:
        fixed binomial blur -> stride-2 sampling -> pointwise Conv

    Branch 2:
        MaxPool - AvgPool local contrast -> pointwise Conv

    The two branches use shared ECA-generated channel logits and
    channel-wise softmax competition.

    Current PAN interfaces:
        layer 24:  64 -> 64,   160x160 -> 80x80
        layer 28:  64 -> 64,    80x80 -> 40x40
        layer 32: 128 -> 128,    40x40 -> 20x20
    """

    def __init__(
        self,
        c1: int,
        c2: int,
        eca_kernel: int = 3,
    ):
        super().__init__()

        if c1 <= 0:
            raise ValueError(
                f"c1 must be positive, got {c1}."
            )

        if c2 <= 0 or c2 % 2 != 0:
            raise ValueError(
                f"SCADown requires positive even c2, got {c2}."
            )

        if eca_kernel <= 0 or eca_kernel % 2 == 0:
            raise ValueError(
                "eca_kernel must be a positive odd number, "
                f"got {eca_kernel}."
            )

        self.c1 = int(c1)
        c_half = c2 // 2

        # --------------------------------------------------
        # 1. Low-frequency anti-alias branch
        # --------------------------------------------------
        self.low_pw = Conv(
            c1,
            c_half,
            k=1,
            s=1,
        )

        # --------------------------------------------------
        # 2. Local-contrast detail branch
        # --------------------------------------------------
        self.contrast_pw = Conv(
            c1,
            c_half,
            k=1,
            s=1,
        )

        # --------------------------------------------------
        # 3. Shared ECA branch selector
        #
        # One shared Conv1d processes the GAP descriptors of
        # both branches. The resulting logits compete through
        # a two-branch channel-wise softmax.
        # --------------------------------------------------
        self.branch_eca = nn.Conv1d(
            in_channels=1,
            out_channels=1,
            kernel_size=eca_kernel,
            padding=(eca_kernel - 1) // 2,
            bias=False,
        )

        # sigmoid/softmax-neutral initialization
        nn.init.zeros_(self.branch_eca.weight)

        # --------------------------------------------------
        # 4. Fixed 3x3 binomial low-pass filter
        #
        # [1, 2, 1]^T [1, 2, 1] / 16
        # --------------------------------------------------
        kernel_1d = torch.tensor(
            [1.0, 2.0, 1.0],
            dtype=torch.float32,
        )

        kernel_2d = (
            kernel_1d[:, None]
            * kernel_1d[None, :]
        )

        kernel_2d = kernel_2d / kernel_2d.sum()

        blur_kernel = kernel_2d.reshape(
            1,
            1,
            3,
            3,
        ).repeat(
            c1,
            1,
            1,
            1,
        )

        self.register_buffer(
            "blur_kernel",
            blur_kernel,
            persistent=True,
        )

    @staticmethod
    def channel_shuffle(
        x: torch.Tensor,
        groups: int = 2,
    ) -> torch.Tensor:
        batch, channels, height, width = x.shape

        if channels % groups != 0:
            raise ValueError(
                f"Channels {channels} must be divisible "
                f"by shuffle groups {groups}."
            )

        x = x.reshape(
            batch,
            groups,
            channels // groups,
            height,
            width,
        )

        x = x.transpose(1, 2).contiguous()

        return x.reshape(
            batch,
            channels,
            height,
            width,
        )

    def _eca_logits(
        self,
        x: torch.Tensor,
    ) -> torch.Tensor:
        """
        Convert one branch into channel-selection logits.

        Input:
            [B, C, H, W]

        Output:
            [B, C, 1, 1]
        """

        descriptor = x.mean(
            dim=(2, 3),
            keepdim=False,
        )

        # [B,C] -> [B,1,C]
        descriptor = descriptor.unsqueeze(1)

        logits = self.branch_eca(descriptor)

        # [B,1,C] -> [B,C,1,1]
        logits = logits.squeeze(1)
        logits = logits.unsqueeze(-1).unsqueeze(-1)

        return logits

    def forward(
        self,
        x: torch.Tensor,
    ) -> torch.Tensor:
        if x.shape[1] != self.c1:
            raise ValueError(
                "SCADown received unexpected input channels: "
                f"expected {self.c1}, got {x.shape[1]}."
            )

        # --------------------------------------------------
        # Low-frequency branch
        #
        # Strictly low-pass first, then subsample.
        # The fixed kernel is depthwise and introduces no
        # trainable parameters.
        # --------------------------------------------------
        low = F.conv2d(
            x,
            self.blur_kernel,
            bias=None,
            stride=2,
            padding=1,
            groups=self.c1,
        )

        low = self.low_pw(low)

        # --------------------------------------------------
        # Local-contrast branch
        #
        # MaxPool retains local peaks.
        # Subtracting AvgPool removes the slowly varying
        # local water-surface baseline.
        # --------------------------------------------------
        local_max = F.max_pool2d(
            x,
            kernel_size=3,
            stride=2,
            padding=1,
        )

        local_avg = F.avg_pool2d(
            x,
            kernel_size=3,
            stride=2,
            padding=1,
        )

        contrast = local_max - local_avg
        contrast = self.contrast_pw(contrast)

        # --------------------------------------------------
        # Channel-wise competition between both branches
        # --------------------------------------------------
        low_logits = self._eca_logits(low)
        contrast_logits = self._eca_logits(contrast)

        branch_logits = torch.stack(
            (low_logits, contrast_logits),
            dim=0,
        )

        branch_weights = torch.softmax(
            branch_logits.float(),
            dim=0,
        ).to(
            device=x.device,
            dtype=x.dtype,
        )

        # Multiplication by 2 keeps both branch amplitudes
        # equal to 1 at zero initialization.
        branch_weights = 2.0 * branch_weights

        low = branch_weights[0] * low
        contrast = branch_weights[1] * contrast

        output = torch.cat(
            (low, contrast),
            dim=1,
        )

        return self.channel_shuffle(
            output,
            groups=2,
        )

class RMADown(nn.Module):
    """Residual Mixed-Attention ADown.

    Structure:
        ADown main branch
        -> factorized local-spatial/global-channel attention
        -> zero-initialized low-frequency residual shortcut
    """

    def __init__(
        self,
        c1: int,
        c2: int,
        channel_kernel: int = 5,
        gate_scale: float = 0.5,
    ):
        """Initialize RMADown.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            channel_kernel (int): Conv1d kernel used by global
                channel attention.
            gate_scale (float): Maximum residual attention amplitude.
                The default 0.5 bounds attention weights to [0.5, 1.5].
        """
        super().__init__()

        if c1 <= 0 or c2 <= 0:
            raise ValueError(
                f"c1 and c2 must be positive, got c1={c1}, c2={c2}"
            )

        # ADown divides both input and output channels into two branches.
        if c1 % 2 != 0 or c2 % 2 != 0:
            raise ValueError(
                "RMADown requires even input and output channels, "
                f"got c1={c1}, c2={c2}"
            )

        if channel_kernel < 1 or channel_kernel % 2 == 0:
            raise ValueError(
                "channel_kernel must be a positive odd integer, "
                f"got {channel_kernel}"
            )

        if gate_scale < 0.0:
            raise ValueError(
                f"gate_scale must be non-negative, got {gate_scale}"
            )

        self.gate_scale = float(gate_scale)

        # Main downsampling path: reuse the project's original ADown.
        self.main = ADown(c1, c2)

        # Local spatial branch:
        # channel mean/max -> [B,2,H,W] -> [B,1,H,W].
        self.local_gate = nn.Conv2d(
            2,
            1,
            kernel_size=3,
            stride=1,
            padding=1,
            bias=True,
        )

        # Global channel branch:
        # GAP -> [B,1,C] -> Conv1d -> [B,C,1,1].
        self.channel_gate = nn.Conv1d(
            1,
            1,
            kernel_size=channel_kernel,
            stride=1,
            padding=channel_kernel // 2,
            bias=False,
        )

        # Initial attention logits are zero:
        # 1 + gate_scale * tanh(0) = 1.
        nn.init.zeros_(self.local_gate.weight)
        nn.init.zeros_(self.local_gate.bias)
        nn.init.zeros_(self.channel_gate.weight)

        # Learnable local/global mixing ratio:
        # sigmoid(0) = 0.5 at initialization.
        self.mix_logit = nn.Parameter(torch.zeros(1))

        # Full-channel low-frequency residual shortcut.
        self.shortcut = Conv(
            c1,
            c2,
            k=1,
            s=1,
            act=False,
        )

        # Make the residual output exactly zero at initialization.
        # Ultralytics initialize_weights() does not overwrite these values.
        nn.init.zeros_(self.shortcut.bn.weight)
        nn.init.zeros_(self.shortcut.bn.bias)

    def _mixed_attention(self, x: torch.Tensor) -> torch.Tensor:
        """Generate factorized local-spatial/global-channel weights."""
        # Local spatial descriptor:
        # [B,C,H,W] -> [B,2,H,W].
        local_descriptor = torch.cat(
            (
                x.mean(dim=1, keepdim=True),
                x.amax(dim=1, keepdim=True),
            ),
            dim=1,
        )
        local_logits = self.local_gate(local_descriptor)

        # Global channel descriptor:
        # [B,C,H,W] -> [B,C,1,1] -> [B,1,C].
        channel_descriptor = F.adaptive_avg_pool2d(x, 1)
        channel_descriptor = channel_descriptor.squeeze(-1).transpose(1, 2)

        # [B,1,C] -> [B,C,1,1].
        channel_logits = self.channel_gate(channel_descriptor)
        channel_logits = channel_logits.transpose(1, 2).unsqueeze(-1)

        # Keep the learned scalar in the same dtype as the activations.
        # This prevents AMP FP16 output from being promoted to FP32.
        rho = torch.sigmoid(self.mix_logit).to(dtype=x.dtype)

        attention_logits = (
            rho * local_logits
            + (1.0 - rho) * channel_logits
        )

        # Bounded residual gate:
        # gate_scale=0.5 -> attention in [0.5,1.5].
        return 1.0 + self.gate_scale * torch.tanh(attention_logits)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply RMA downsampling."""
        main = self.main(x)
        main = main * self._mixed_attention(main)

        # Pool first and then use stride-1 1×1 Conv.
        # This remains aligned with ADown even for odd input sizes.
        shortcut = F.avg_pool2d(
            x,
            kernel_size=2,
            stride=2,
            padding=0,
            ceil_mode=False,
            count_include_pad=True,
        )
        shortcut = self.shortcut(shortcut)

        # Normally this is a no-op, but it protects AMP output dtype.
        shortcut = shortcut.to(dtype=main.dtype)

        return main + shortcut

class SPPELAN(nn.Module):
    """SPP-ELAN."""

    def __init__(self, c1: int, c2: int, c3: int, k: int = 5):
        """Initialize SPP-ELAN block.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            c3 (int): Intermediate channels.
            k (int): Kernel size for max pooling.
        """
        super().__init__()
        self.c = c3
        self.cv1 = Conv(c1, c3, 1, 1)
        self.cv2 = nn.MaxPool2d(kernel_size=k, stride=1, padding=k // 2)
        self.cv3 = nn.MaxPool2d(kernel_size=k, stride=1, padding=k // 2)
        self.cv4 = nn.MaxPool2d(kernel_size=k, stride=1, padding=k // 2)
        self.cv5 = Conv(4 * c3, c2, 1, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass through SPPELAN layer."""
        y = [self.cv1(x)]
        y.extend(m(y[-1]) for m in [self.cv2, self.cv3, self.cv4])
        return self.cv5(torch.cat(y, 1))


class CBLinear(nn.Module):
    """CBLinear."""

    def __init__(self, c1: int, c2s: list[int], k: int = 1, s: int = 1, p: int | None = None, g: int = 1):
        """Initialize CBLinear module.

        Args:
            c1 (int): Input channels.
            c2s (list[int]): List of output channel sizes.
            k (int): Kernel size.
            s (int): Stride.
            p (int | None): Padding.
            g (int): Groups.
        """
        super().__init__()
        self.c2s = c2s
        self.conv = nn.Conv2d(c1, sum(c2s), k, s, autopad(k, p), groups=g, bias=True)

    def forward(self, x: torch.Tensor) -> list[torch.Tensor]:
        """Forward pass through CBLinear layer."""
        return self.conv(x).split(self.c2s, dim=1)


class CBFuse(nn.Module):
    """CBFuse."""

    def __init__(self, idx: list[int]):
        """Initialize CBFuse module.

        Args:
            idx (list[int]): Indices for feature selection.
        """
        super().__init__()
        self.idx = idx

    def forward(self, xs: list[torch.Tensor]) -> torch.Tensor:
        """Forward pass through CBFuse layer.

        Args:
            xs (list[torch.Tensor]): List of input tensors.

        Returns:
            (torch.Tensor): Fused output tensor.
        """
        target_size = xs[-1].shape[2:]
        res = [F.interpolate(x[self.idx[i]], size=target_size, mode="nearest") for i, x in enumerate(xs[:-1])]
        return torch.sum(torch.stack(res + xs[-1:]), dim=0)


class C3f(nn.Module):
    """Faster Implementation of CSP Bottleneck with 3 convolutions."""

    def __init__(self, c1: int, c2: int, n: int = 1, shortcut: bool = False, g: int = 1, e: float = 0.5):
        """Initialize CSP bottleneck layer with three convolutions.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            n (int): Number of Bottleneck blocks.
            shortcut (bool): Whether to use shortcut connections.
            g (int): Groups for convolutions.
            e (float): Expansion ratio.
        """
        super().__init__()
        c_ = int(c2 * e)  # hidden channels
        self.cv1 = Conv(c1, c_, 1, 1)
        self.cv2 = Conv(c1, c_, 1, 1)
        self.cv3 = Conv((2 + n) * c_, c2, 1)  # optional act=FReLU(c2)
        self.m = nn.ModuleList(Bottleneck(c_, c_, shortcut, g, k=((3, 3), (3, 3)), e=1.0) for _ in range(n))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass through C3f layer."""
        y = [self.cv2(x), self.cv1(x)]
        y.extend(m(y[-1]) for m in self.m)
        return self.cv3(torch.cat(y, 1))


class C3k2(C2f):
    """Faster Implementation of CSP Bottleneck with 2 convolutions."""

    def __init__(
        self,
        c1: int,
        c2: int,
        n: int = 1,
        c3k: bool = False,
        e: float = 0.5,
        attn: bool = False,
        g: int = 1,
        shortcut: bool = True,
    ):
        """Initialize C3k2 module.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            n (int): Number of blocks.
            c3k (bool): Whether to use C3k blocks.
            e (float): Expansion ratio.
            attn (bool): Whether to use attention blocks.
            g (int): Groups for convolutions.
            shortcut (bool): Whether to use shortcut connections.
        """
        super().__init__(c1, c2, n, shortcut, g, e)
        self.m = nn.ModuleList(
            nn.Sequential(
                Bottleneck(self.c, self.c, shortcut, g),
                PSABlock(self.c, attn_ratio=0.5, num_heads=max(self.c // 64, 1)),
            )
            if attn
            else C3k(self.c, self.c, 2, shortcut, g)
            if c3k
            else Bottleneck(self.c, self.c, shortcut, g)
            for _ in range(n)
        )

class DPWFP2Fusion(nn.Module):
    """
    Dual-path Private/Common Weighted Fusion for P2.

    Input order:
        x[0]: upsampled P3 semantic feature
        x[1]: BSQ-enhanced B2 detail feature

    Output:
        common semantic channels + private difference channels
    """

    def __init__(
        self,
        c_semantic: int,
        c_detail: int,
        c_out: int,
        private_groups: int = 4,
    ):
        super().__init__()

        if c_out < 3:
            raise ValueError(f"c_out must be >= 3, got {c_out}.")

        self.common_ch = (2 * c_out) // 3
        self.private_ch = c_out - self.common_ch

        if (
            2 * self.common_ch % private_groups != 0
            or self.private_ch % private_groups != 0
        ):
            raise ValueError(
                "private_groups must divide both the private input "
                f"and output channels, got c_out={c_out}, "
                f"groups={private_groups}."
            )

        self.semantic_proj = (
            nn.Identity()
            if c_semantic == self.common_ch
            else Conv(c_semantic, self.common_ch, k=1, s=1)
        )
        self.detail_proj = (
            nn.Identity()
            if c_detail == self.common_ch
            else Conv(c_detail, self.common_ch, k=1, s=1)
        )

        # 每个通道分别学习语义、细节分支的归一化权重。
        # 零初始化后 softmax 权重为 0.5 / 0.5。
        self.fusion_logits = nn.Parameter(
            torch.zeros(2, self.common_ch, 1, 1)
        )

        # 从两路相对公共特征的差异中提取私有信息。
        self.private_proj = Conv(
            2 * self.common_ch,
            self.private_ch,
            k=1,
            s=1,
            g=private_groups,
        )

        # 让新差异分支从较小幅度开始参与训练。
        self.private_scale = nn.Parameter(torch.tensor(0.1))

    def forward(self, x):
        if not isinstance(x, (list, tuple)) or len(x) != 2:
            raise ValueError(
                "DPWFP2Fusion expects "
                "[upsampled_P3, B2_detail] as two inputs."
            )

        semantic, detail = x

        if semantic.shape[-2:] != detail.shape[-2:]:
            raise ValueError(
                "DPWFP2Fusion input spatial sizes must match, got "
                f"{semantic.shape[-2:]} and {detail.shape[-2:]}."
            )

        semantic = self.semantic_proj(semantic)
        detail = self.detail_proj(detail)

        weights = torch.softmax(
            self.fusion_logits.float(),
            dim=0,
        ).to(device=semantic.device, dtype=semantic.dtype)

        common = (
            weights[0] * semantic
            + weights[1] * detail
        )

        private_input = torch.cat(
            (
                detail - common,
                semantic - common,
            ),
            dim=1,
        )

        private = self.private_proj(private_input)
        private = torch.tanh(self.private_scale) * private

        return torch.cat((common, private), dim=1)

class SGDFuseP2(nn.Module):
    """
    Semantic-Guided Detail-Preserving Fusion for P2.

    Input order:
        x[0]: upsampled P3 semantic feature
        x[1]: BSQ-enhanced B2 detail feature

    Current n-model:
        semantic: 64 x 160 x 160
        detail:   64 x 160 x 160
        output:   64 x 160 x 160
    """

    def __init__(
        self,
        c_semantic: int,
        c_detail: int,
        c_out: int,
        gate_reduction: int = 4,
        dilation: int = 2,
        residual_scale: float = 0.1,
    ):
        super().__init__()

        if c_out <= 0 or c_out % 2 != 0:
            raise ValueError(
                f"SGDFuseP2 requires positive even c_out, got {c_out}."
            )

        if gate_reduction <= 0:
            raise ValueError(
                "gate_reduction must be positive, "
                f"got {gate_reduction}."
            )

        if dilation <= 0:
            raise ValueError(
                f"dilation must be positive, got {dilation}."
            )

        c_half = c_out // 2
        c_gate = max(c_detail // gate_reduction, 8)

        # --------------------------------------------------
        # 1. Upsampled P3 semantic branch
        # DWConv helps smooth nearest-neighbor block artifacts.
        # --------------------------------------------------
        self.semantic_dw = DWConv(
            c_semantic,
            c_semantic,
            k=3,
            s=1,
        )

        self.semantic_pw = Conv(
            c_semantic,
            c_half,
            k=1,
            s=1,
        )

        # --------------------------------------------------
        # 2. Blur-aware B2' detail branch
        # Standard DW3: clear small targets
        # Dilated DW3: blurry/diffused small targets
        # --------------------------------------------------
        self.detail_dw3 = nn.Conv2d(
            c_detail,
            c_detail,
            kernel_size=3,
            stride=1,
            padding=1,
            groups=c_detail,
            bias=False,
        )

        self.detail_dwd = nn.Conv2d(
            c_detail,
            c_detail,
            kernel_size=3,
            stride=1,
            padding=dilation,
            dilation=dilation,
            groups=c_detail,
            bias=False,
        )

        self.detail_norm = nn.BatchNorm2d(c_detail)
        self.detail_act = nn.SiLU(inplace=True)

        # Per-channel branch weights.
        # Zero initialization gives 0.5 / 0.5.
        self.detail_logits = nn.Parameter(
            torch.zeros(2, c_detail, 1, 1)
        )

        # --------------------------------------------------
        # 3. P3 semantic channel gate for B2' detail
        # Zero-initialized final layer gives an identity gate.
        # --------------------------------------------------
        self.gate_pool = nn.AdaptiveAvgPool2d(1)

        self.gate_fc1 = nn.Conv2d(
            c_semantic,
            c_gate,
            kernel_size=1,
            bias=True,
        )

        self.gate_act = nn.SiLU(inplace=True)

        self.gate_fc2 = nn.Conv2d(
            c_gate,
            c_detail,
            kernel_size=1,
            bias=True,
        )

        nn.init.zeros_(self.gate_fc2.weight)
        nn.init.zeros_(self.gate_fc2.bias)

        self.detail_pw = Conv(
            c_detail,
            c_half,
            k=1,
            s=1,
        )

        # --------------------------------------------------
        # 4. Lightweight semantic/detail update
        # --------------------------------------------------
        self.update = Conv(
            c_out,
            c_out,
            k=1,
            s=1,
            act=False,
        )

        # B2' retains a complete identity path in the current model.
        self.detail_skip = (
            nn.Identity()
            if c_detail == c_out
            else Conv(
                c_detail,
                c_out,
                k=1,
                s=1,
                act=False,
            )
        )

        # Per-channel residual strength.
        self.gamma = nn.Parameter(
            torch.full(
                (1, c_out, 1, 1),
                float(residual_scale),
            )
        )

    def forward(self, x):
        if not isinstance(x, (list, tuple)) or len(x) != 2:
            raise ValueError(
                "SGDFuseP2 expects exactly two inputs: "
                "[upsampled_P3, B2_detail]."
            )

        semantic, detail = x

        if semantic.shape[-2:] != detail.shape[-2:]:
            raise ValueError(
                "SGDFuseP2 input spatial sizes must match, got "
                f"{semantic.shape[-2:]} and {detail.shape[-2:]}."
            )

        # P3 semantic residual.
        semantic_update = self.semantic_pw(
            self.semantic_dw(semantic)
        )

        # Clear/blurry detail adaptive selection.
        branch_weights = torch.softmax(
            self.detail_logits.float(),
            dim=0,
        ).to(
            device=detail.device,
            dtype=detail.dtype,
        )

        detail_update = (
            branch_weights[0] * self.detail_dw3(detail)
            + branch_weights[1] * self.detail_dwd(detail)
        )

        detail_update = self.detail_act(
            self.detail_norm(detail_update)
        )

        # P3 global semantics recalibrate detail channels.
        gate = self.gate_pool(semantic)
        gate = self.gate_fc1(gate)
        gate = self.gate_act(gate)
        gate = torch.tanh(self.gate_fc2(gate))

        detail_update = detail_update * (1.0 + gate)
        detail_update = self.detail_pw(detail_update)

        update = torch.cat(
            (semantic_update, detail_update),
            dim=1,
        )
        update = self.update(update)

        # Do not add another activation here:
        # this keeps B2' as a genuine residual identity path.
        return (
            self.detail_skip(detail)
            + self.gamma * update
        )

class _PartialConv3(nn.Module):
    """Apply a 3x3 convolution to only part of the channels."""

    def __init__(self, channels: int, n_div: int = 2):
        super().__init__()

        if n_div < 1:
            raise ValueError(f"n_div must be positive, got {n_div}.")

        self.conv_channels = channels // n_div
        self.identity_channels = channels - self.conv_channels

        if self.conv_channels < 1:
            raise ValueError(
                f"channels={channels} is too small for n_div={n_div}."
            )

        self.partial_conv = nn.Conv2d(
            self.conv_channels,
            self.conv_channels,
            kernel_size=3,
            stride=1,
            padding=1,
            bias=False,
        )

    def forward(self, x):
        spatial, identity = torch.split(
            x,
            [self.conv_channels, self.identity_channels],
            dim=1,
        )
        spatial = self.partial_conv(spatial)
        return torch.cat((spatial, identity), dim=1)


class _PFasterBlock(nn.Module):
    """Partial spatial mixing followed by a lightweight channel MLP."""

    def __init__(
        self,
        channels: int,
        n_div: int = 2,
        mlp_ratio: float = 2.0,
    ):
        super().__init__()

        hidden_channels = max(
            channels,
            int(channels * mlp_ratio),
        )

        self.spatial_mixing = _PartialConv3(
            channels,
            n_div=n_div,
        )

        self.channel_mixing = nn.Sequential(
            Conv(
                channels,
                hidden_channels,
                k=1,
                s=1,
            ),
            nn.Conv2d(
                hidden_channels,
                channels,
                kernel_size=1,
                stride=1,
                padding=0,
                bias=False,
            ),
        )

        self.act = nn.SiLU(inplace=True)

    def forward(self, x):
        residual = x
        x = self.spatial_mixing(x)
        x = self.channel_mixing(x)
        return self.act(residual + x)


