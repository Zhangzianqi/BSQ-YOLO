class RDGSC3k2P2(nn.Module):
    """
    Retained-Detail GS lightweight replacement for the P2 C3k2.

    Expected input:
        Concat[
            upsampled P3 semantic feature,
            BSQ-enhanced B2' detail feature
        ]

    Current n-model:
        input:  128 x 160 x 160
        output:  64 x 160 x 160

    The second half of the input is the original B2' detail feature,
    which is retained through a complete identity path.
    """

    def __init__(
        self,
        c1: int,
        c2: int,
        eca_kernel: int = 3,
        residual_scale: float = 0.1,
    ):
        super().__init__()

        if c1 != 2 * c2:
            raise ValueError(
                "RDGSC3k2P2 expects input channels to equal "
                f"2 * output channels, got c1={c1}, c2={c2}."
            )

        if c2 <= 0 or c2 % 2 != 0:
            raise ValueError(
                f"c2 must be positive and even, got {c2}."
            )

        if eca_kernel <= 0 or eca_kernel % 2 == 0:
            raise ValueError(
                "eca_kernel must be a positive odd number, "
                f"got {eca_kernel}."
            )

        self.c2 = int(c2)
        hidden_channels = c2 // 2

        # --------------------------------------------------
        # GS residual branch
        #
        # Dense 1x1 convolution:
        #   mixes P3 semantic and B2' detail information.
        #
        # DW5:
        #   generates inexpensive context-aware features
        #   for blurry and weak small targets.
        # --------------------------------------------------
        self.primary = Conv(
            c1,
            hidden_channels,
            k=1,
            s=1,
        )

        self.cheap = DWConv(
            hidden_channels,
            hidden_channels,
            k=5,
            s=1,
        )

        # --------------------------------------------------
        # Lightweight ECA channel recalibration
        # --------------------------------------------------
        self.pool = nn.AdaptiveAvgPool2d(1)

        self.eca = nn.Conv1d(
            in_channels=1,
            out_channels=1,
            kernel_size=eca_kernel,
            padding=(eca_kernel - 1) // 2,
            bias=False,
        )

        # Initial ECA weight=0 gives sigmoid(0)=0.5,
        # avoiding random channel suppression at initialization.
        nn.init.zeros_(self.eca.weight)

        # Small residual start protects the original B2' detail.
        self.gamma = nn.Parameter(
            torch.tensor(float(residual_scale))
        )

    @staticmethod
    def channel_shuffle(
        x: torch.Tensor,
        groups: int = 2,
    ) -> torch.Tensor:
        batch, channels, height, width = x.shape

        if channels % groups != 0:
            raise ValueError(
                f"Channels {channels} must be divisible "
                f"by shuffle groups {groups}."
            )

        x = x.reshape(
            batch,
            groups,
            channels // groups,
            height,
            width,
        )

        x = x.transpose(1, 2).contiguous()

        return x.reshape(
            batch,
            channels,
            height,
            width,
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if x.shape[1] != 2 * self.c2:
            raise ValueError(
                "RDGSC3k2P2 received unexpected channels: "
                f"expected {2 * self.c2}, got {x.shape[1]}."
            )

        # Concat order is:
        # [upsampled P3 semantic, B2' detail].
        _, detail = x.split(
            (self.c2, self.c2),
            dim=1,
        )

        # Standard-convolution intrinsic features.
        primary = self.primary(x)

        # Cheap large-receptive-field features.
        cheap = self.cheap(primary)

        residual = torch.cat(
            (primary, cheap),
            dim=1,
        )

        residual = self.channel_shuffle(
            residual,
            groups=2,
        )

        # ECA:
        # [B,C,1,1] -> [B,1,C] -> [B,C,1,1]
        channel_weight = self.pool(residual)
        channel_weight = channel_weight.squeeze(-1)
        channel_weight = channel_weight.transpose(-1, -2)

        channel_weight = self.eca(channel_weight)
        channel_weight = torch.sigmoid(channel_weight)

        channel_weight = channel_weight.transpose(-1, -2)
        channel_weight = channel_weight.unsqueeze(-1)

        residual = residual * channel_weight

        # Genuine B2' detail identity:
        # no final activation is added after the residual addition.
        return (
            detail
            + torch.tanh(self.gamma) * residual
        )

class C3k(C3):
    """C3k is a CSP bottleneck module with customizable kernel sizes for feature extraction in neural networks."""

    def __init__(self, c1: int, c2: int, n: int = 1, shortcut: bool = True, g: int = 1, e: float = 0.5, k: int = 3):
        """Initialize C3k module.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            n (int): Number of Bottleneck blocks.
            shortcut (bool): Whether to use shortcut connections.
            g (int): Groups for convolutions.
            e (float): Expansion ratio.
            k (int): Kernel size.
        """
        super().__init__(c1, c2, n, shortcut, g, e)
        c_ = int(c2 * e)  # hidden channels
        # self.m = nn.Sequential(*(RepBottleneck(c_, c_, shortcut, g, k=(k, k), e=1.0) for _ in range(n)))
        self.m = nn.Sequential(*(Bottleneck(c_, c_, shortcut, g, k=(k, k), e=1.0) for _ in range(n)))


class RepVGGDW(torch.nn.Module):
    """RepVGGDW is a class that represents a depth-wise convolutional block in RepVGG architecture."""

    def __init__(self, ed: int) -> None:
        """Initialize RepVGGDW module.

        Args:
            ed (int): Input and output channels.
        """
        super().__init__()
        self.conv = Conv(ed, ed, 7, 1, 3, g=ed, act=False)
        self.conv1 = Conv(ed, ed, 3, 1, 1, g=ed, act=False)
        self.dim = ed
        self.act = nn.SiLU()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Perform a forward pass of the RepVGGDW block.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor after applying the depth-wise convolution.
        """
        return self.act(self.conv(x) + self.conv1(x))

    def forward_fuse(self, x: torch.Tensor) -> torch.Tensor:
        """Perform a forward pass of the fused RepVGGDW block.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor after applying the depth-wise convolution.
        """
        return self.act(self.conv(x))

    @torch.no_grad()
    def fuse(self):
        """Fuse the convolutional layers in the RepVGGDW block.

        This method fuses the convolutional layers and updates the weights and biases accordingly.
        """
        if not hasattr(self, "conv1"):
            return  # already fused
        conv = fuse_conv_and_bn(self.conv.conv, self.conv.bn)
        conv1 = fuse_conv_and_bn(self.conv1.conv, self.conv1.bn)

        conv_w = conv.weight
        conv_b = conv.bias
        conv1_w = conv1.weight
        conv1_b = conv1.bias

        conv1_w = torch.nn.functional.pad(conv1_w, [2, 2, 2, 2])

        final_conv_w = conv_w + conv1_w
        final_conv_b = conv_b + conv1_b

        conv.weight.data.copy_(final_conv_w)
        conv.bias.data.copy_(final_conv_b)

        self.conv = conv
        del self.conv1


class CIB(nn.Module):
    """Compact Inverted Block (CIB) module.

    Args:
        c1 (int): Number of input channels.
        c2 (int): Number of output channels.
        shortcut (bool, optional): Whether to add a shortcut connection. Defaults to True.
        e (float, optional): Scaling factor for the hidden channels. Defaults to 0.5.
        lk (bool, optional): Whether to use RepVGGDW for the third convolutional layer. Defaults to False.
    """

    def __init__(self, c1: int, c2: int, shortcut: bool = True, e: float = 0.5, lk: bool = False):
        """Initialize the CIB module.

        Args:
            c1 (int): Input channels.
            c2 (int): Output channels.
            shortcut (bool): Whether to use shortcut connection.
            e (float): Expansion ratio.
            lk (bool): Whether to use RepVGGDW.
        """
        super().__init__()
        c_ = int(c2 * e)  # hidden channels
        self.cv1 = nn.Sequential(
            Conv(c1, c1, 3, g=c1),
            Conv(c1, 2 * c_, 1),
            RepVGGDW(2 * c_) if lk else Conv(2 * c_, 2 * c_, 3, g=2 * c_),
            Conv(2 * c_, c2, 1),
            Conv(c2, c2, 3, g=c2),
        )

        self.add = shortcut and c1 == c2

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass of the CIB module.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        return x + self.cv1(x) if self.add else self.cv1(x)


